'use strict';

/**
 * Narration for a Muse job.
 *
 * The worker never calls a provider API. The Muse environment writes the
 * narration through MUSE_SCRIPT_COMMAND, or an operating agent writes
 * script.txt itself and uses `muse-agent.js deliver`.
 */

const fs = require('fs');
const path = require('path');
const { minimumScriptWords } = require('../lib/mediaRules');
const { runCommand, parseJsonOutput, quoteArg } = require('../lib/command');
const { registerStageProcess } = require('../lib/stageCleanup');
const { assertNoOpenRouterKey } = require('../lib/museInference');

function minimumWords(job) {
  return minimumScriptWords(job.targetDurationMinutes || 8);
}

function normalizeScriptResult(parsed) {
  if (typeof parsed === 'string') return { scriptText: parsed.trim(), meta: {} };
  if (!parsed || typeof parsed !== 'object') return null;
  const scriptText = String(parsed.scriptText || parsed.script || parsed.narration || '').trim();
  if (!scriptText) return null;
  return {
    scriptText,
    meta: parsed.meta && typeof parsed.meta === 'object' ? parsed.meta : {}
  };
}

function validateScript(text, job) {
  const scriptText = String(text || '').trim();
  const words = scriptText.split(/\s+/).filter(Boolean).length;
  const requiredWords = minimumWords(job);
  const warnings = [];
  if (!scriptText) return { ok: false, words: 0, minimumWords: requiredWords, warnings, error: 'Narration is empty' };
  if (words < requiredWords) {
    return {
      ok: false,
      words,
      minimumWords: requiredWords,
      warnings,
      error: `Narration is too short for ${job.targetDurationMinutes || 8} minutes (${words} words; at least ${requiredWords} needed)`
    };
  }
  return { ok: true, words, minimumWords: requiredWords, warnings };
}

async function runScriptCommand(command, job, workDir, { signal, onDetail, expansion, timeoutMs } = {}) {
  const payload = {
    type: 'script',
    job,
    workDir,
    scriptPath: path.join(workDir, 'script.txt'),
    requirements: job.requirements || {}
  };
  if (expansion) payload.expansion = expansion;
  const result = await runCommand(command, {
    input: JSON.stringify(payload),
    cwd: workDir,
    signal,
    timeoutMs: Number(timeoutMs) || Number(process.env.MUSE_SCRIPT_TIMEOUT_MS) || 10 * 60 * 1000,
    label: 'Muse script command',
    onSpawn: spawn => registerStageProcess(job.jobId, 'script', spawn),
    env: {
      MUSE_JOB_ID: job.jobId,
      MUSE_WORK_DIR: workDir,
      MUSE_STAGE: 'script',
      MUSE_EXPANSION: expansion ? '1' : '0'
    }
  });
  const parsed = parseJsonOutput(result.stdout);
  const normalized = normalizeScriptResult(parsed ?? result.stdout);
  if (!normalized) throw new Error('Muse script command returned no narration text');
  onDetail?.('Narration generated by the configured Muse agent command');
  return normalized;
}

function saveScript(workDir, scriptText, meta = {}) {
  const file = path.join(workDir, 'script.txt');
  fs.writeFileSync(file, String(scriptText).trim() + '\n', 'utf8');
  fs.writeFileSync(path.join(workDir, 'script-meta.json'), JSON.stringify({
    ...meta,
    savedAt: new Date().toISOString()
  }, null, 2) + '\n', 'utf8');
  return file;
}

function readSavedScript(workDir) {
  const file = path.join(workDir, 'script.txt');
  try {
    const scriptText = fs.readFileSync(file, 'utf8').trim();
    return scriptText || '';
  } catch {
    return '';
  }
}

function synthesizeNarration(job) {
  const title = String(job.title || 'Documentary Investigation').trim();
  const premise = String(job.premise || job.description || 'An in-depth documentary exploring the operational reality, technical history, and documented record.').trim();
  const channelName = String(job.channel?.name || 'Documentary Archive').trim();
  const niche = String(job.channel?.niche || 'Documentary').trim();
  const hook = String(job.titlePackage?.hook || '').trim();
  const targetWords = minimumWords(job);

  const hookIntro = hook
    ? `${hook} This fundamental question stands at the center of ${title}. In this documentary, we trace the documented facts, the structural decisions, and the pivotal turning points that defined what unfolded.`
    : `When we look closely at the history of ${title}, few chapters offer as much clarity and unexpected depth. Behind the familiar headlines lies a documented sequence of events, structural decisions, and critical moments that shaped the outcome. In this investigation, we examine the primary evidence, separating the myth from the documented reality.`;

  const sections = [
    hookIntro,

    `To understand how this story developed, we must first establish the context that surrounded it. ${premise} Rather than an isolated incident or an abrupt coincidence, the reality was driven by a convergence of technological, organizational, and historical pressures. Observers at the time noted the growing momentum, yet the full significance of these early indicators would only become apparent as the key actors committed to their respective courses of action.`,

    `As events progressed toward their central turning point, the operational mechanics revealed themselves with absolute precision. In fields within ${niche.toLowerCase()}, success and stability depend on exacting standards, where small oversights cascade into far-reaching consequences. Archival records and primary documentation demonstrate how every decision brought compound effects, forcing leadership and participants to confront challenges that had never previously been tested under such rigorous conditions.`,

    `What makes ${title} particularly compelling in hindsight is the structural discipline that governed each phase. Far from arbitrary, the choices made were anchored in specific principles, calculated tradeoffs, and the relentless pressure of their operating environment. Eyewitness accounts, technical audits, and contemporary documentation all point to a singular conclusion: the pivotal breakthroughs and catastrophic failures alike were the direct consequence of human decisions made under uncompromising constraints.`,

    `In reflecting on this legacy through ${channelName}, we gain a broader perspective on the systemic realities that continue to influence modern practice. By returning to the documented record, analyzing the causal chain step by step, and interrogating the underlying mechanics, the story of ${title} moves beyond simplified lore into an enduring case study in perseverance, strategy, and consequence.`
  ];

  let script = sections.join('\n\n');
  let currentWords = script.split(/\s+/).filter(Boolean).length;

  let iteration = 1;
  const expansionTopics = [
    `Delving deeper into the archival records of ${title}, chapter ${iteration} highlights the technical evaluations and evidentiary reviews conducted in the aftermath. Contemporary analysts cataloged the precise timelines, verifying that procedural discipline remained the deciding factor across every major milestone.`,
    `Furthermore, examining the structural impact of these events reveals how institutions and practitioners adapted their methodologies in response. The documented outcomes of ${title} established lasting benchmarks, demonstrating that verifiable standards and rigorous execution supersede short-term expediency.`,
    `A critical dimension often overlooked in retrospective accounts is the logistical and operational framework that underpinned these efforts. Through meticulous documentation and primary testimony, researchers have mapped the interplay of resource allocation and strategic foresight that ultimately governed the outcome of ${title}.`
  ];

  while (currentWords < targetWords) {
    const topic = expansionTopics[(iteration - 1) % expansionTopics.length];
    script += '\n\n' + topic;
    currentWords = script.split(/\s+/).filter(Boolean).length;
    iteration += 1;
  }

  return script;
}

async function generateScript(job, workDir, { signal, onDetail, onProgress } = {}) {
  const command = String(process.env.MUSE_SCRIPT_COMMAND || '').trim();

  const saved = readSavedScript(workDir);
  if (saved) {
    const check = validateScript(saved, job);
    if (check.ok) {
      onDetail?.(`Reusing the saved narration (${check.words} words)`);
      return { scriptText: saved, words: check.words, resumed: true, meta: { engine: 'saved-script' } };
    }
  }

  // Template fallback is opt-in only. The old synthesizer pads generic
  // paragraphs to a word count; it is not a researched script and must never
  // be the silent default.
  if (!command && process.env.MUSE_SCRIPT_ALLOW_TEMPLATE_FALLBACK === '1') {
    onProgress?.(15, 'Template fallback enabled: synthesizing generic narration (not a researched script)');
    const synthesized = synthesizeNarration(job);
    const check = validateScript(synthesized, job);
    if (!check.ok) {
      throw new Error(`Synthesized narration failed validation: ${check.error}`);
    }
    saveScript(workDir, synthesized, { engine: 'template-synthesizer-generic', words: check.words });
    onDetail?.(`Generic template narration ready (${check.words} words)`);
    return { scriptText: synthesized, words: check.words, resumed: false, meta: { engine: 'template-synthesizer-generic' } };
  }

  // Muse inference is compulsory: an OpenRouter key in the environment
  // would make ScriptIT pick OpenRouter over the agent-bridge. Refuse
  // before any script command runs — a script must never be written by
  // another provider, and the template fallback below stays opt-in only.
  assertNoOpenRouterKey(process.env);

  // Default engine: the ScriptIT headless CLI. In agent-bridge mode it needs
  // no OpenRouter key — Muse answers its inference requests through the
  // Vidnets inbox. A custom MUSE_SCRIPT_COMMAND still wins when set.
  const scriptitCli = path.join(__dirname, '..', 'scriptit', 'cli', 'generate.js');
  const isDefault = !command;
  const effectiveCommand = command || `node ${quoteArg(scriptitCli)}`;
  // Agent-bridge round-trips are human-speed (inbox + operator); give the
  // default engine a 45-minute budget. A custom command keeps the 10-minute
  // default unless MUSE_SCRIPT_TIMEOUT_MS overrides it.
  const timeoutMs = Number(process.env.MUSE_SCRIPT_TIMEOUT_MS)
    || (isDefault ? 45 * 60 * 1000 : 10 * 60 * 1000);

  onProgress?.(10, isDefault ? 'Generating narration with ScriptIT (agent-bridge mode)' : 'Generating narration with the Muse agent');
  let result = await runScriptCommand(effectiveCommand, job, workDir, { signal, onDetail, timeoutMs });
  let check = validateScript(result.scriptText, job);

  // SIMPLIFIED PIPELINE (Nov 9, 2026): the script is written ONCE. The old
  // default re-ran the whole ScriptIT generation (research + drafts) when
  // the narration came back short — a second full generation hiding inside
  // the adapter. Expansion is now opt-in only (MUSE_SCRIPT_EXPAND_ON_SHORT=1);
  // otherwise a short script fails loudly here with a clear message.
  if (!check.ok && process.env.MUSE_SCRIPT_EXPAND_ON_SHORT === '1') {
    onDetail?.(`Narration returned ${check.words} of ${check.minimumWords} words; requesting one bounded expansion`);
    onProgress?.(45, 'Narration is short; requesting one bounded expansion');
    try {
      const expanded = await runScriptCommand(effectiveCommand, job, workDir, {
        signal,
        onDetail,
        timeoutMs,
        expansion: {
          requiredWords: check.minimumWords,
          previousWords: check.words,
          previousScript: result.scriptText,
          instruction: 'Continue the same narration to the requested runtime. Keep every supported fact, do not repeat the introduction, and return the complete narration.'
        }
      });
      const expandedCheck = validateScript(expanded.scriptText, job);
      if (expandedCheck.ok || expandedCheck.words > check.words) {
        result = expanded;
        check = expandedCheck;
      }
    } catch (error) {
      if (signal?.aborted) throw error;
      onDetail?.('Expansion request failed; keeping the original narration: ' + error.message);
    }
  }

  if (!check.ok) {
    throw new Error(
      `${check.error}. The job needs complete narration for the requested runtime; ` +
      'shorten the requested runtime in the CMS or generate more narration. No rendered master was produced.'
    );
  }

  saveScript(workDir, result.scriptText, { engine: isDefault ? 'scriptit' : 'command', meta: result.meta || {}, words: check.words });
  return { ...result, meta: { ...(result.meta || {}), engine: isDefault ? 'scriptit' : 'command' }, words: check.words, resumed: false };
}

module.exports = {
  minimumScriptWords: minimumWords,
  validateScript,
  generateScript,
  synthesizeNarration,
  normalizeScriptResult,
  saveScript,
  readSavedScript
};
