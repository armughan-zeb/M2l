'use strict';

/**
 * Narration for a Muse job (One-Minute Documentary or 2D Stickman).
 *
 * Precedence:
 *   1. Saved `work/<jobId>/script.txt` (if valid for this job)
 *   2. Explicit `MUSE_SCRIPT_COMMAND` override
 *   3. Compulsory Muse inference (`inferWithMuse`) — zero OpenRouter
 */

const fs = require('fs');
const path = require('path');
const { minimumScriptWords } = require('../lib/mediaRules');
const { runCommand, parseJsonOutput } = require('../lib/command');
const { registerStageProcess } = require('../lib/stageCleanup');
const { assertNoOpenRouterKey } = require('../lib/museInference');
const { writeJsonAtomic } = require('../lib/config');
const { resolveVideoStyle, ENGINES } = require('../lib/videoStyle');
const { inferWithMuse, resolveOverrideCommand } = require('../lib/museBridgeInfer');

function minimumWords(job) {
  return minimumScriptWords(job.targetDurationMinutes || 1);
}

function resolveScriptEngine(env = process.env) {
  if (resolveOverrideCommand(env.MUSE_SCRIPT_COMMAND, { envName: 'MUSE_SCRIPT_COMMAND', warnOnStale: false })) return 'command';
  return 'muse-inference';
}

function normalizeScriptResult(parsed) {
  if (typeof parsed === 'string') return { scriptText: parsed.trim(), meta: {} };
  if (!parsed || typeof parsed !== 'object') return null;
  const scriptText = String(parsed.scriptText || parsed.script || parsed.narration || '').trim();
  if (!scriptText) return null;
  return {
    scriptText,
    meta: parsed.meta && typeof parsed.meta === 'object' ? parsed.meta : {}
  };
}

function validateScript(text, job) {
  const scriptText = String(text || '').trim();
  const words = scriptText.split(/\s+/).filter(Boolean).length;
  const requiredWords = minimumWords(job);
  const warnings = [];
  if (!scriptText) return { ok: false, words: 0, minimumWords: requiredWords, warnings, error: 'Narration is empty' };
  if (words < requiredWords) {
    warnings.push(`Narration is shorter than the requested ${job.targetDurationMinutes || 1}-minute runtime (${words} words; target ${requiredWords})`);
    return { ok: true, words, minimumWords: requiredWords, warnings, error: '' };
  }
  return { ok: true, words, minimumWords: requiredWords, warnings };
}

async function runScriptCommand(command, job, workDir, { signal, onDetail, expansion, timeoutMs } = {}) {
  const payload = {
    type: 'script',
    job,
    workDir,
    scriptPath: path.join(workDir, 'script.txt'),
    requirements: job.requirements || {}
  };
  if (expansion) payload.expansion = expansion;
  let result;
  try {
    result = await runCommand(command, {
      input: JSON.stringify(payload),
      cwd: workDir,
      signal,
      timeoutMs: Number(timeoutMs) || Number(process.env.MUSE_SCRIPT_TIMEOUT_MS) || 10 * 60 * 1000,
      label: 'Muse script command',
      onSpawn: spawn => registerStageProcess(job.jobId, 'script', spawn),
      env: {
        MUSE_JOB_ID: job.jobId,
        MUSE_WORK_DIR: workDir,
        MUSE_STAGE: 'script',
        MUSE_EXPANSION: expansion ? '1' : '0'
      }
    });
  } catch (error) {
    const response = parseJsonOutput(error.stdout);
    const detail = response && typeof response.error === 'string' && response.error.trim();
    const failure = detail
      ? new Error(`Muse script command failed for job ${job.jobId} (script stage): ${detail}`, { cause: error })
      : new Error(`Muse script command failed for job ${job.jobId} (script stage): ${error.message}`, { cause: error });
    failure.code = error.code;
    if (!signal?.aborted) {
      try {
        writeJsonAtomic(path.join(workDir, 'script-error.json'), {
          jobId: job.jobId, exitCode: error.code ?? null,
          error: String(failure.message).slice(0, 2000), recordedAt: new Date().toISOString()
        }, { mode: 0o600 });
      } catch { /* ignore */ }
    }
    throw failure;
  }
  const parsed = parseJsonOutput(result.stdout);
  if (typeof parsed?.error === 'string' && parsed.error.trim()) {
    throw new Error(`Muse script command failed for job ${job.jobId} (script stage): ` + parsed.error.trim());
  }
  const normalized = normalizeScriptResult(parsed ?? result.stdout);
  if (!normalized) throw new Error(`Muse script command for job ${job.jobId} returned no narration text`);
  onDetail?.('Narration generated by the configured Muse agent command');
  return normalized;
}

function buildScriptMessages(job) {
  const style = resolveVideoStyle(job);
  const targetMinutes = Math.max(1, Number(job.targetDurationMinutes) || 1);
  const targetWords = Number(job.targetWordCount) || Math.round(targetMinutes * 150);
  const minWords = minimumWords(job);
  const title = String(job.title || 'Untitled').trim();
  const premise = String(job.premise || job.description || '').trim();
  const hook = String(job.titlePackage?.hook || '').trim();
  const angle = String(job.titlePackage?.angle || '').trim();
  const audience = String(job.titlePackage?.targetAudience || '').trim();
  const channelName = String(job.channel?.name || '').trim();
  const niche = String(job.channel?.niche || '').trim();
  const subniche = String(job.channel?.subniche || '').trim();
  const persona = String(job.channel?.persona || job.channel?.notes || job.channel?.description || '').trim();
  const tone = String(job.channel?.scriptSettings?.tone || '').trim();
  const customStructure = String(job.channel?.scriptSettings?.customStructure || '').trim();
  const rules = String(job.channel?.scriptSettings?.rules || '').trim();
  const guidelines = String(job.channel?.scriptSettings?.guidelines || '').trim();
  const refTranscript = String(
    job.titlePackage?.referenceTranscript ||
    job.channel?.scriptSettings?.referenceTranscript ||
    job.scriptReferences?.[0]?.transcript || ''
  ).trim().slice(0, 1800);

  const isStickman = style.engine === ENGINES.STICKMAN;
  const sys = isStickman
    ? [
        `Write spoken narration for a ${targetMinutes}-minute 2D Stickman Cartoon Studio video (\`2d-stickman\`).`,
        `IMPORTANT DURATION TARGET: Write ~${targetWords} words (minimum ${minWords} words) to fill the full ${targetMinutes}-minute CMS runtime at ~150 words/minute.`,
        'Rules:',
        '1. Use punchy, visual, action-driven sentences (~8-15 words per sentence) that work naturally with animated stickman scenes.',
        '2. Spell out numbers, years, and acronyms as they should be spoken.',
        '3. Output plain spoken narration paragraphs ONLY — no headings, no markdown, no stage directions.',
        '4. Be factually accurate; do not invent statistics or claims.',
        rules ? `5. Channel script rules: ${rules}` : '',
      ].filter(Boolean).join('\n')
    : [
        `Write full-length spoken narration for a ${targetMinutes}-minute Remotion documentary video (\`one_minute_documentary\` template).`,
        `IMPORTANT DURATION TARGET: Write ~${targetWords} words (minimum ${minWords} words) so spoken narration covers the entire ${targetMinutes}-minute CMS runtime (~150 words/minute). Never write a short 1-minute summary when ${targetMinutes} > 1.`,
        customStructure
          ? `Follow this structure: ${customStructure}`
          : 'Follow the five documentary beats scaled proportionally to the full runtime: 1) Hook, 2) Background / Origins, 3) Development / Turning points, 4) Impact, 5) Closing reflection.',
        'Rules:',
        '1. Spell numbers and dates as they should sound when spoken aloud.',
        '2. Output plain spoken narration paragraphs ONLY — no markdown, no headings, no bullet lists, no stage directions.',
        '3. Ground every claim in documented reality; never invent facts or filler repetition.',
        rules ? `4. Channel script rules: ${rules}` : '',
      ].filter(Boolean).join('\n');

  const userParts = [
    `TITLE: ${title}`,
    `TARGET_DURATION_MINUTES: ${targetMinutes} (~${targetWords} words target, >= ${minWords} words)`,
    channelName ? `CHANNEL: ${channelName}${niche ? ` (${niche}${subniche ? ` / ${subniche}` : ''})` : ''}` : '',
    persona ? `CHANNEL_PERSONA: ${persona}` : '',
    premise ? `PREMISE: ${premise}` : '',
    hook ? `HOOK: ${hook}` : '',
    angle ? `ANGLE: ${angle}` : '',
    audience ? `TARGET_AUDIENCE: ${audience}` : '',
    tone ? `TONE: ${tone}` : '',
    guidelines ? `GUIDELINES: ${guidelines}` : '',
    refTranscript ? `REFERENCE STYLE EXCERPT:\n${refTranscript}` : '',
  ].filter(Boolean);

  return [
    { role: 'system', content: sys },
    { role: 'user', content: userParts.join('\n\n') },
  ];
}

function saveScript(workDir, scriptText, meta = {}) {
  const file = path.join(workDir, 'script.txt');
  fs.writeFileSync(file, String(scriptText).trim() + '\n', 'utf8');
  fs.writeFileSync(path.join(workDir, 'script-meta.json'), JSON.stringify({
    ...meta,
    savedAt: new Date().toISOString()
  }, null, 2) + '\n', 'utf8');
  return file;
}

function readSavedScript(workDir) {
  const file = path.join(workDir, 'script.txt');
  try {
    const scriptText = fs.readFileSync(file, 'utf8').trim();
    return scriptText || '';
  } catch {
    return '';
  }
}

async function generateScript(job, workDir, { signal, onDetail, onProgress, inferFn } = {}) {
  const command = resolveOverrideCommand(process.env.MUSE_SCRIPT_COMMAND, { envName: 'MUSE_SCRIPT_COMMAND' });

  const saved = readSavedScript(workDir);
  if (saved) {
    const check = validateScript(saved, job);
    if (check.ok) {
      onDetail?.(`Reusing the saved narration (${check.words} words)`);
      return { scriptText: saved, words: check.words, resumed: true, meta: { engine: 'saved-script' } };
    }
  }

  assertNoOpenRouterKey(process.env);

  if (command) {
    const timeoutMs = Number(process.env.MUSE_SCRIPT_TIMEOUT_MS) || 10 * 60 * 1000;
    onProgress?.(10, 'Generating narration with the Muse script command');
    const result = await runScriptCommand(command, job, workDir, { signal, onDetail, timeoutMs });
    const check = validateScript(result.scriptText, job);
    if (!check.ok) throw new Error(check.error);
    saveScript(workDir, result.scriptText, { ...result.meta, engine: 'command', words: check.words });
    return { ...result, words: check.words, resumed: false };
  }

  const style = resolveVideoStyle(job);
  const operation = style.engine === ENGINES.STICKMAN ? 'stickman_script' : 'documentary_script';
  onProgress?.(12, `Generating ${style.label} narration via Muse inference`);
  const reply = await inferWithMuse({
    operation,
    kind: 'text',
    messages: buildScriptMessages(job),
    jobId: job.jobId,
    workDir,
    timeoutMs: Number(process.env.MUSE_SCRIPT_TIMEOUT_MS) || 15 * 60 * 1000,
    signal,
    inferFn,
    json: false,
  });

  const scriptText = String(reply.data || '').trim();
  const check = validateScript(scriptText, job);
  if (!check.ok) {
    throw new Error(`${check.error}. Muse returned unusable narration.`);
  }
  if (check.warnings.length) onDetail?.(check.warnings.join('; '));
  saveScript(workDir, scriptText, { engine: 'muse-inference', operation, inferRequestId: reply.id, words: check.words });
  onDetail?.(`Narration ready (${check.words} words)`);
  return {
    scriptText,
    words: check.words,
    resumed: false,
    meta: { engine: 'muse-inference', operation, inferRequestId: reply.id, publishable: true }
  };
}

module.exports = {
  minimumWords,
  resolveScriptEngine,
  normalizeScriptResult,
  validateScript,
  buildScriptMessages,
  generateScript,
  saveScript,
  readSavedScript
};
